# Backwards-compatible alias: the old preset name now yields the needs_counsel tag (2026-10 retag; see CHANGELOG.md).
PRESETS["multisensegolf_cc0"] = PRESETS["multisensegolf_needs_counsel"]


def preset(kind: str, **overrides) -> Dict:
    if kind not in PRESETS:
        raise ValueError(f"unknown provenance kind {kind!r}; choose from {sorted(PRESETS)}")
    d = dict(PRESETS[kind]); d.update(overrides)
    if d["license_class"] not in LICENSE_CLASSES:
        raise ValueError(f"bad license_class {d['license_class']!r}")
    return d


def tag(data: Dict, kind: str, overwrite: bool = False, **overrides) -> Dict:
    """Return `data` (mutated) with provenance keys added as 0-d arrays."""
    if not overwrite and "license_class" in data:
        return data
    for k, v in preset(kind, **overrides).items():
        data[k] = np.array(v, dtype=bool) if isinstance(v, bool) else np.array(str(v))
    return data


def infer_kind(name: str, arrays: Optional[Dict] = None) -> str:
    """Best-effort kind from file name / existing metadata."""
    arrays = arrays or {}
    src = str(arrays["source"]) if "source" in arrays else ""
    style = str(arrays["style"]) if "style" in arrays else ""
    low = f"{name} {src} {style}".lower()
    if any(w in low for w in ("golfdb", "amass", "sportspose", "rep3d", "golfpose", "caddieset")):
        return "noncommercial"
    if "multisense" in low:
        return "multisensegolf_needs_counsel"
    if "cmu" in low:
        return "cmu_mocap"
    if "mason" in low:
        return "mason_self_filmed"
    if "is_synthetic" in arrays and bool(arrays["is_synthetic"]):
        return "synthetic"
    if style in ("scott", "scheffler", "rory", "average") and "source" not in arrays:
        return "synthetic"
    return "unknown"


def read_tags(path) -> Dict:
    """Tags of a file; missing keys -> unknown defaults (commercial_ok False)."""
    try:
        with np.load(path, allow_pickle=True) as d:
            if "license_class" not in d.files:
                return {**PRESETS["unknown"], "tagged": False}
            out = {k: d[k].item() for k in TAG_KEYS if k in d.files}
            out["commercial_ok"] = bool(out.get("commercial_ok", False))
            out["tagged"] = True
            return out
    except Exception:
        return {**PRESETS["unknown"], "tagged": False}


def include_commercial_only(paths: Iterable) -> List:
    """Filter to files whose tags say commercial_ok. Untagged/unreadable files are excluded."""
    return [p for p in paths if read_tags(p)["commercial_ok"]]


def save_npz_atomic(path, arrays: Dict) -> None:
    path = Path(path)
    tmp = path.with_name(path.stem + ".tagtmp.npz")
    try:
        np.savez(tmp, **arrays)
        os.replace(tmp, path)
    finally:
        if tmp.exists():
            tmp.unlink()


