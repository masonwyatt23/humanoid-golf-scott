#!/usr/bin/env python3
"""Generate docs/RESULTS_DASHBOARD.md from committed results (stdlib only).

Sources: results/leaderboard.json and results/strike_regime_rerun.json.
Every number is read from those files; nothing is typed by hand.
Run: python scripts/gen_results_dashboard.py [--check]
"""
import json, math, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "docs", "RESULTS_DASHBOARD.md")


def load(name):
    with open(os.path.join(ROOT, "results", name), encoding="utf-8") as f:
        return json.load(f)


def num(x, fmt="{:.1f}", scale=1.0):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "n/a"
    return fmt.format(x * scale)


def pct(x):
    return num(x, "{:.0f}%", 100.0)


def mode_row(m):
    return [pct(m.get("contact_rate")), num(m.get("mean_carry")), num(m.get("lateral_std"), "{:.2f}"),
            num(m.get("launch_elev_mean_deg")), num(m.get("peak_club_mph_mean"))]


HEAD = ["Model", "Contact", "Carry (m)", "Lateral std (m)", "Launch (deg)", "Peak club (mph)"]


def table(rows, head=HEAD):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join(["---"] * len(head)) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out


def main():
    lb = load("leaderboard.json")
    sr = load("strike_regime_rerun.json")
    models = lb["models"]
    def name(m):
        return " / ".join(m["names"])
    lines = ["# Results dashboard", "",
             "_Auto-generated by `scripts/gen_results_dashboard.py` from `results/leaderboard.json` and "
             "`results/strike_regime_rerun.json`. Do not edit by hand; rerun the script._", "",
             f"- Episodes per evaluation: {lb['episodes']} (seed base {lb['seed_base']}); "
             f"env fingerprint `{lb['env_fingerprint']}`.",
             f"- Qualifying criterion recorded in the leaderboard: `{json.dumps(lb['qualify_criterion'])}`.",
             f"- Models qualifying under that criterion: {lb['qualifying'] if lb['qualifying'] else 'none'}.",
             "- Deterministic = policy mean action; stochastic = sampled actions. They are never averaged here.",
             "- Caveat: leaderboard rows use each model's own recorded config. Several learned rows come from "
             "the older strike regime and do not hold under the corrected one (see the last section).",
             "- Carry is in metres. `n/a` means the file has no value (for example no contact).", ""]
    for scripted, title in ((True, "Scripted (not learned)"), (False, "Learned (PPO policies)")):
        sel = [m for m in models if bool(m.get("scripted")) == scripted]
        lines += [f"## {title}", ""]
        for mode, label in (("deterministic", "Deterministic"), ("stochastic", "Stochastic")):
            rows = [[name(m)] + mode_row(m["modes"][mode]) for m in sel if mode in m.get("modes", {})]
            rows.sort(key=lambda r: -(float(r[2]) if r[2] != "n/a" else -1))
            lines += [f"### {title}: {label}", ""] + table(rows) + [""]
    lines += ["## Strike-regime re-evaluation", "",
              f"Same checkpoints evaluated under their original config (OLD) and under the corrected strike "
              f"regime (NEW, out of distribution for trained policies). {sr['episodes']} episodes, seed {sr['seed']}.", ""]
    head = ["Row", "Kind", "Mode", "Contact", "Carry (m)", "Lateral std (m)", "Launch (deg)", "Club (mph)"]
    for kind_title, is_scripted in (("Scripted", True), ("Learned", False)):
        rows = []
        for r in sr["rows"]:
            if ("SCRIPTED" in r["kind"].upper()) != is_scripted:
                continue
            for mode in ("deterministic", "stochastic"):
                d = r.get(mode)
                if d:
                    rows.append([r["label"], r["kind"], mode, pct(d.get("contact")), num(d.get("carry")),
                                 num(d.get("lat_std"), "{:.2f}"), num(d.get("launch")), num(d.get("mph"))])
        lines += [f"### {kind_title}", ""] + table(rows, head) + [""]
    text = "\n".join(lines).rstrip() + "\n"
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur != text:
            print("docs/RESULTS_DASHBOARD.md is stale; run scripts/gen_results_dashboard.py")
            return 1
        print("dashboard up to date")
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
